import type { MaterialCategory } from '@kujiale/scene-schema';

export type ProceduralPatternKind =
  | 'wood_planks'
  | 'ceramic_tiles'
  | 'marble_veins'
  | 'terrazzo'
  | 'concrete_aggregate'
  | 'brick_bond'
  | 'plaster_fine'
  | 'smooth_coat'
  | 'woven_fabric'
  | 'pebble_leather'
  | 'grass_turf'
  | 'corrugated_metal'
  | 'terracotta_tiles'
  | 'glass';

export interface PbrMaterialSpec {
  id: string;
  name: string;
  category: MaterialCategory;
  pattern: ProceduralPatternKind;
  /** Optional CC0 Poly Haven scanned PBR pack in /textures/<texturePackId>/{diff,nor_gl,arm}.jpg */
  texturePackId?: string;
  /** Optional multiplicative sRGB tint applied over scanned diffuse map */
  tintHex?: string;
  /** Optional linear albedo brightness multiplier for dark scanned diffuse maps */
  albedoGain?: number;
  baseColorHex: string;
  secondaryColorHex: string;
  roughness: number;
  metalness: number;
  bumpStrength: number;
  /** Physical width/height in metres covered by 1.0 UV tile */
  tileSizeMeters: number;
  clearcoat?: number;
  clearcoatRoughness?: number;
  sheen?: number;
  sheenRoughness?: number;
  sheenColorHex?: string;
  transmission?: number;
  opacity?: number;
  envMapIntensity?: number;
  recommendedFor: Array<'floor' | 'wall' | 'exterior_wall' | 'roof' | 'furniture'>;
}

